// CLEARTEXT ONLY TO THE CONFIGURED LAN HOST(S) (spec 034 FR6). Android's network security config cannot
// wildcard an IP range or change at runtime, so the LAN host(s) are fixed at build time:
// `cb.lanHosts=192.168.1.20` in android/local.properties (gitignored), or `-Pcb.lanHosts=…`. Each
// must be an RFC 1918 IPv4 literal or the build fails; everything else stays TLS-only.
val lanHosts: List<String> = run {
    val props = Properties()
    val f = rootProject.file("local.properties")
    if (f.exists()) f.inputStream().use { props.load(it) }
    val raw = (project.findProperty("cb.lanHosts") as String?) ?: props.getProperty("cb.lanHosts") ?: ""
    raw.split(",").map { it.trim() }.filter { it.isNotEmpty() }
}
fun isPrivateV4(h: String): Boolean {
    val p = h.split(".")
    if (p.size != 4) return false
    val o = p.map { s -> s.toIntOrNull()?.takeIf { it in 0..255 && s == it.toString() } ?: return false }
    return o[0] == 10 || (o[0] == 172 && o[1] in 16..31) || (o[0] == 192 && o[1] == 168)
}
lanHosts.forEach { require(isPrivateV4(it)) { "cb.lanHosts: '$it' is not a private (RFC 1918) IPv4 address" } }
val nscRes = layout.buildDirectory.dir("generated/nsc/res").get().asFile
run {
    val loopback = listOf("localhost", "127.0.0.1", "10.0.2.2")
    val domains = (loopback + lanHosts).joinToString("\n") { "        <domain includeSubdomains=\"false\">$it</domain>" }
    val out = File(nscRes, "xml/network_security_config.xml")
    out.parentFile.mkdirs()
    out.writeText("""<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by app/build.gradle.kts (spec 034 FR6); edit cb.lanHosts, not this file.
     Plain http/ws only to loopback (an emulator's 10.0.2.2 included) and the configured LAN host(s);
     everything else must be TLS (the tunnel's https URL). -->
<network-security-config>
    <base-config cleartextTrafficPermitted="false" />
    <domain-config cleartextTrafficPermitted="true">
$domains
    </domain-config>
</network-security-config>
""")
}

